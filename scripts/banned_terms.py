"""異世界ニホン変換で使用が問題となりうる語のリスト。

scripts/validate.py(生成された下書きの検査)と
tests/test_rule_consistency.py(ルールファイル自体の検査)の両方から
参照する。同じリストを複数箇所に重複定義しないためのモジュール。

## 王制関連語の扱い(2026-07-18改訂)
「国王」「女王」「王家」「王族」「王子」「王女」「王妃」「王都」等の語
そのものは、実在する法律用語(皇室典範上の身位)・外国の君主号・歴史上
の呼称として現実の記事に正当に登場しうるため、単語単位の無条件禁止語
にはしない。

禁止するのは、入力記事に存在しない「ニホン+王制語」の固定複合表現
(ニホンに実在しない王制を創作する表現)だけである。ある複合表現が
入力記事に同一の文字列として存在する場合(引用・否定説明等の可能性が
あるため)は自動NGにしない。

「統治する」「支配する」等、文全体の意味理解が必要な主張の真偽は、
正規表現では安全に判定できない(否定文・語順違い・共起関係の誤認を
避けられない)。例えば以下は正規表現の単純な共起判定では区別できない:
- 女王がニホンを統治している(創作、問題)
- 女王がニホンを統治している事実はない(正しい否定)
- ニホンに国王や女王が統治する制度は存在しない(正しい否定)
- 英国国王が来日し、ニホンの統治制度について説明を受けた(無関係な共起)
そのため scripts/validate.py の自動検査の対象から意図的に除外する。
この種の問題は config/runtime_rules.md の禁止規則と、生成後の人間/
Codexレビューで確認する運用とする。

入力語彙の存在は「その語自体を禁止理由にしない」ことだけを保証する。
その語を使って入力にない関係性・統治状態を創作していないかは、この
自動検査では保証できない(runtime_rules.mdと生成後レビューの対象)。
"""

